/** Prefix for the synthetic ids given to a level's fixed anchor tiles -- never a real
 *  deck id, so it can never collide with one of the hand's tiles. */
const POINT_TILE_PREFIX = 'point-';

export function isPointTileId(tileId: string): boolean {
  return tileId.startsWith(POINT_TILE_PREFIX);
}

/** A fresh board holding just the level's anchor points, nothing else. */
export function initialPuzzleBoard(level: PuzzleLevel): Board {
  let board = emptyBoard();
  level.points.forEach((point, i) => {
    board = placeTile(board, `${POINT_TILE_PREFIX}${i}`, point.cell, point.values);
  });
  return board;
}

/** True once every one of the level's points sits in the same edge-connected group of
 *  placed tiles -- a plain BFS from the first point that has to reach all the others. */
export function isPuzzleSolved(board: Board, level: PuzzleLevel): boolean {
  const startKey = cellKey(level.points[0].cell);
  if (!board[startKey]) return false;

  const goalKeys = new Set(level.points.slice(1).map((p) => cellKey(p.cell)));
  for (const key of goalKeys) if (!board[key]) return false;
  if (goalKeys.size === 0) return true;

  const seen = new Set([startKey]);
  const queue: CellCoord[] = [level.points[0].cell];
  while (queue.length > 0) {
    const cur = queue.shift()!;
    for (const neighbor of edgeNeighbors(cur)) {
      const key = cellKey(neighbor);
      goalKeys.delete(key);
      if (goalKeys.size === 0) return true;
      if (board[key] && !seen.has(key)) {
        seen.add(key);
        queue.push(neighbor);
      }
    }
  }
  return false;
}

const PROGRESS_KEY = 'triominos:puzzleprogress';

/** Set of level ids the player has solved at least once. */
export function loadPuzzleProgress(): Set<string> {
  try {
    const raw = localStorage.getItem(PROGRESS_KEY);
    if (!raw) return new Set();
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) ? new Set(parsed.filter((id) => typeof id === 'string')) : new Set();
  } catch {
    return new Set();
  }
}

export function markPuzzleSolved(levelId: string): Set<string> {
  const solved = loadPuzzleProgress();
  solved.add(levelId);
  try {
    localStorage.setItem(PROGRESS_KEY, JSON.stringify([...solved]));
  } catch {
    // Storage can be unavailable (private mode); progress just won't persist.
  }
  return solved;
}
